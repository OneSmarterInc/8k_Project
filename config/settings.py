# ---------------------------------------------------------------------
# .env loading
#
# This project has NO python-dotenv dependency (see requirements.txt),
# so we load backend/.env with the standard library only.
#
# Rules:
#   - real environment variables always win over .env
#   - blank lines and "#" comments are ignored
#   - "export KEY=value" is accepted
#   - surrounding single/double quotes are stripped
# ---------------------------------------------------------------------

def _load_env_file(env_path: Path) -> None:
    if not env_path.is_file():
        return

    try:
        raw_text = env_path.read_text(encoding="utf-8-sig")
    except (OSError, UnicodeDecodeError):
        return

    for raw_line in raw_text.splitlines():
        line = raw_line.strip()

        if not line or line.startswith("#"):
            continue

        if line.lower().startswith("export "):
            line = line[len("export "):].strip()

        if "=" not in line:
            continue

        key, _, value = line.partition("=")

        key = key.strip()
        value = value.strip()

        if len(value) >= 2 and value[0] == value[-1] and value[0] in ("'", '"'):
            value = value[1:-1]

        if key and key not in os.environ:
            os.environ[key] = value


_load_env_file(BASE_DIR / ".env")


def _env_str(name, default=""):
    return os.environ.get(name, default).strip()


def _env_int(name, default):
    try:
        return int(_env_str(name, str(default)))
    except ValueError:
        return default

def _env_bool(name, default=False):
    value = os.environ.get(name)
    if value is None:
        return default
    return value.strip().lower() in {"1", "true", "yes", "on"}


def _env_list(name, default=""):
    return [
        item.strip()
        for item in _env_str(name, default).split(",")
        if item.strip()
    ]


def _env_float(name, default):
    try:
        return float(_env_str(name, str(default)))
    except ValueError:
        return default


